namespace Hexara.Application.Players;

/// <summary>
/// رنگ آواتار کاربران.
///
/// اینجا در Application نشسته چون هر سه لایه لازمش دارند: پیش‌فرضِ ستون در
/// Infrastructure، ساختِ هویت مهمان در Web، و جایگزینِ نمای بازی در همین لایه.
/// سه نسخه‌ی جدا از یک فهرست رنگ، همان چیزی است که تا امروز باعث شد رنگ‌های
/// نشانِ قدیمی در گوشه‌وکنار جا بمانند.
///
/// **این فهرست با <c>--hx-seat-1..6</c> یکی نیست و نمی‌تواند باشد.** رنگ صندلی
/// روی مهره‌ی سه‌بعدی می‌نشیند و هیچ متنی حمل نمی‌کند، ولی آواتار حرف اول نام را
/// روی خودش می‌نویسد. اندازه‌گیری‌شده: قرمز و آبی و قهوه‌ایِ صندلی در برابر مرکبِ
/// آواتار فقط ۳.۰۸ تا ۳.۳۰ می‌دهند — زیر حد ۴.۵.
///
/// هر رنگ تازه‌ای که اضافه می‌کنی باید ۴.۵:۱ با <see cref="Ink"/> بدهد و از بقیه
/// به‌قدر کافی دور بماند؛ <c>AvatarPaletteTests</c> هر دو را می‌سنجد.
/// </summary>
public static class AvatarPalette
{
    /// <summary>
    /// مرکبی که حرف اول نام با آن روی آواتار نوشته می‌شود — همان
    /// <c>--hx-avatar-ink</c> در توکن‌ها.
    ///
    /// عمداً با تم عوض نمی‌شود: رنگ آواتار هویتِ کاربر است، مثل مهره‌ی بازی، و
    /// یک مهره با روشن‌شدن چراغ اتاق رنگ عوض نمی‌کند. مهم‌تر اینکه **هیچ رنگی
    /// نمی‌تواند با هر دو مرکبِ تم ۴.۵:۱ بدهد** — اندازه‌گیری‌شده باید هم‌زمان
    /// ‎L ≥ 0.2133‎ و ‎L ≤ 0.1669‎ باشد که ناممکن است. پس مرکب ثابت می‌ماند و
    /// پالت به‌قدری روشن است که همین یک مرکب همه‌جا بخواند.
    /// </summary>
    public const string Ink = "#241305";

    /// <summary>
    /// ده رنگِ دنیای پارشمنت. ترتیبشان عمدی است: هر رنگ در همان جایی نشسته که
    /// رنگِ هم‌خانواده‌اش در پالت قبلی بود، تا مهاجرت هویت رنگی کاربرها را حفظ
    /// کند — کسی که آبی بود آبی می‌ماند.
    /// </summary>
    public static readonly string[] Colors =
    [
        "#e0906b", // رُس
        "#86b4d6", // آبیِ غبارآلود
        "#e6bb52", // طلایی
        "#86bd80", // مریم‌گلی
        "#bfa0d8", // اسطوخودوس
        "#e3959f", // گلِ سرخ
        "#6fbfb0", // فیروزه‌ای
        "#b9bf62", // زیتونی
        "#c3b8a6", // سنگی
        "#e8c88a"  // شنی
    ];

    /// <summary>رنگ پیش‌فرض، برای وقتی که کاربری رنگ ذخیره‌شده ندارد.</summary>
    public const string Default = "#86b4d6";

    /// <summary>رنگی پایدار از روی یک شناسه — هم‌زمان بی‌نیاز از تصادف و قابل تکرار.</summary>
    public static string For(Guid id) => Colors[(int)((uint)id.GetHashCode() % Colors.Length)];
}
